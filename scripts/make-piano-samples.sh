#!/usr/bin/env bash
# Builds piano-samples.js from the Salamander Grand Piano MP3 samples.
#
# Usage: scripts/make-piano-samples.sh <path-to-audio-dir>
#   where the directory is the `audio/` folder of the npm package
#   @audio-samples/piano-mp3-velocity10 (Salamander Grand Piano V3, velocity layer 10).
#
# Each note is trimmed to 3.2 s with a fade-out, mixed to mono and re-encoded,
# then embedded as base64 so the page works offline, from file://, and on any host.
# Samples by Alexander Holm, CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/).
set -euo pipefail
SRC="${1:?path to the sample package audio/ directory}"
cd "$(dirname "$0")/.."
OUT=piano-samples.js
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Note name -> MIDI number. Samples every 3 semitones from C3 to A5 cover C3–G5
# with at most one semitone of pitch shifting.
NOTES="C3:48 D#3:51 F#3:54 A3:57 C4:60 D#4:63 F#4:66 A4:69 C5:72 D#5:75 F#5:78 A5:81"

{
  echo "/* Salamander Grand Piano V3 by Alexander Holm, CC BY 3.0"
  echo "   https://creativecommons.org/licenses/by/3.0/ — trimmed to 3.2 s, mono."
  echo "   Generated by scripts/make-piano-samples.sh. Keys are MIDI note numbers. */"
  echo "window.PIANO_SAMPLES = {"
} > "$OUT"

first=1
for pair in $NOTES; do
  name="${pair%%:*}"; midi="${pair##*:}"
  ffmpeg -v error -y -i "$SRC/${name}v10.mp3" \
    -af "atrim=start=0.005:duration=3.2,asetpts=PTS-STARTPTS,afade=t=out:st=2.5:d=0.7,pan=mono|c0=0.5*c0+0.5*c1" \
    -ar 44100 -c:a libmp3lame -b:a 96k "$TMP/$midi.mp3"
  [ $first -eq 1 ] || echo "," >> "$OUT"
  first=0
  printf '  %s: "%s"' "$midi" "$(base64 -w0 "$TMP/$midi.mp3")" >> "$OUT"
done
printf '\n};\n' >> "$OUT"
echo "Wrote $OUT ($(wc -c < "$OUT") bytes)"
